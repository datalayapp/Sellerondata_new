export const SPEND_TEXT: Readonly<Record<Locale, Readonly<Record<SpendTextKey, string>>>> = { tr, en };

export type Translate = (key: SpendTextKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const table = SPEND_TEXT[locale] ?? SPEND_TEXT.en;
  return (key, vars) => {
    const text = table[key];
    return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
  };
}
