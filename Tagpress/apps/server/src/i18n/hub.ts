export const HUB_LABELS: Record<HubLocale, Record<HubKey, string>> = { tr, en };

export type HubTranslate = (key: HubKey, params?: Record<string, string | number>) => string;

/** Dile göre çevirici; `{ad}` yer tutucuları doldurulur (bilinmeyen yer tutucu olduğu gibi kalır). */
export function hubTranslator(locale: HubLocale): HubTranslate {
  const dict = HUB_LABELS[locale] ?? HUB_LABELS.en;
  return (key, params) => {
    const text = dict[key] ?? HUB_LABELS.tr[key] ?? key;
    return params ? text.replace(/\{(\w+)\}/g, (m, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : m)) : text;
  };
}
